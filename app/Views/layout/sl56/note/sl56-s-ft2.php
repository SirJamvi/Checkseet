    <p>@ : Isi kolom dengan waktu pengerjaan dan nilai (value) pada alat ukur/mesin</p>
    <p>* : Isi kolom (V) bila kondisi OK, dan (X) bila kondisi NG dan bila dikerjakan.</p>
    <p># : Ketika "Emergency Stop" atau "Off" karena mesin trouble, setelah "ON" harus mengecek kondisi device pada semua holder dan pressing-down device biasanya tertutup pada semua holder sebelum "Return to Origin"</p>
